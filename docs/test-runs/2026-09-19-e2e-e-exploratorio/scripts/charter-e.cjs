const L = require('/work/lib.cjs')
const flat = (s) => String(s).replace(/\s+/g, ' ').trim()
;(async () => {
  const b = await L.launch(); const adm = await L.adminLogin()
  const api1 = await L.api('/api/rescue-status-logs', { token: adm.token })
  console.log(`RESULT|RES-119/api-1|OBS|GET /api/rescue-status-logs -> ${api1.status} ${JSON.stringify(api1.json).slice(0, 140)}`)
  const { page } = await L.newCtx(b, {}, { token: adm.token, user: adm.user })
  await page.goto(L.BASE + '/painel/logs'); await L.sleep(2500)
  const alert = flat(await page.locator('.v-alert').allInnerTexts().then((a) => a.join(' | ')))
  const rows = await page.locator('tbody tr').count()
  const first = flat(await page.locator('tbody').innerText()).slice(0, 80)
  console.log(`RESULT|RES-119/ui|OBS|tela de logs: alerta="${alert}" linhas=${rows} tabela="${first}" http=[${page.http.join(', ')}] erros=[${page.errors.join(' | ').slice(0, 120)}]`)
  await L.shot(page, 'res119-logs-quebrada')
  // o painel principal continua funcionando?
  await page.goto(L.BASE + '/painel'); await L.sleep(2000)
  console.log(`RESULT|RES-119/painel-continua|OBS|cards no painel=${await page.locator('.rescue-requests-list .v-card').count()}`)
  const api2 = await L.api('/api/rescue-status-logs', { token: adm.token })
  console.log(`RESULT|RES-119/api-2|OBS|2ª reprodução: GET /api/rescue-status-logs -> ${api2.status}`)
  await b.close()
})()
